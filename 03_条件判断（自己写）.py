"""条件判断练习：游泳池入场票价计算器。

根据年龄、票价、是否会游泳三个输入，用 if/elif 多分支判断并输出对应票价。
"""

# 1. 读取三个输入：年龄、票价（原价）、是否会游泳（"是"比较后得到布尔值 True/False）
age = int(input("请输入年龄："))
prise = int(input("请输入票价："))
can_swim = input("是否会游泳（是/否）：") == "是"

# 2. 按优先级逐层判断（先排非法输入，再按年龄段定票价）
if age < 0 or age >= 120 or prise < 0:    # 年龄/票价为负数或年龄超范围，属于非法输入
    print("请核实您的年龄和票价！")
elif not can_swim:                        # 不会游泳，直接拒绝入场
    print("请勿进入游泳池")
elif 0 <= age <= 5:                       # 0-5 岁儿童免费
    print("儿童可免费进入")
elif 6 <= age <= 17:                      # 6-17 岁打五折
    print(f"您的票价为：{prise * 0.5:.1f}元（打五折）")
elif 18 <= age <= 59:                     # 18-59 岁正常价
    print(f"您的票价为：{prise:.1f}元（正常价）")
elif age >= 60:                           # 60 岁及以上打七折
    print(f"您的票价为：{prise * 0.7:.1f}元（打七折）")
else:
    print("请重试")